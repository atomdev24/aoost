#!/usr/bin/env python3
"""Lift the original homepage's CSS (repo-root index.html) into the aoost blocks, scoped under `.ao`.

Run from cms/:  python3 scripts/port-aoost-css.py
It rewrites src/components/aoost/**/**.styles.ts. Each rule keeps its declarations exactly; only the
selector gets the `.ao` scope, so the styles can't leak into (or be hit by) the rest of the CMS site.
Re-run it if index.html's stylesheet changes.
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
lines = (ROOT / "index.html").read_text().split("\n")
OUT = ROOT / "cms/src/components/aoost"

# 1-based, inclusive line ranges of index.html's <style> block, by the block that owns them.
REGIONS = {
    "kit": [(17, 44), (48, 49), (57, 63), (145, 147), (184, 184), (195, 211), (541, 541), (545, 546), (551, 551), (558, 558)],
    "kitAfter": [(214, 226), (416, 416), (575, 576)],
    "AoostHero": [(185, 194), (392, 392), (529, 538)],
    "AoostProjects": [(47, 47), (52, 54), (66, 74), (388, 390), (396, 403), (542, 544)],
    "AoostViewer": [(77, 83)],
    "AoostJournals": [(229, 386)],
    "AoostTools": [(405, 415)],
    "AoostPlaylistBand": [(87, 142), (149, 180), (418, 427)],
    "AoostDrawingWall": [(430, 524)],
    "AoostRodeo": [(547, 550), (559, 574)],
    "AoostFooter": [(526, 526), (552, 555)],
}

HTML_CLASSES = ("late", "sp-touch", "cv-on", "atom-preview")  # classes the scripts put on <html>

def scope_selector(sel: str) -> str:
    s = sel.strip()
    if not s:
        return s
    if s in (":root", "html"):
        return ".ao"
    if s == "body":
        return ".ao"
    if s == "*":
        return ".ao,.ao *"
    if s == "html.late body":
        return "html.late body:has(.ao)"
    if s == "section":
        return ".ao section:not(.s)"  # .s is the CMS's own section wrapper
    for c in HTML_CLASSES:
        if s.startswith("." + c + " "):
            return "html." + c + " " + scope_selector(s[len(c) + 2:])
    if s.startswith(".wrap"):
        return ".ao" + s
    if s.startswith(".editing "):
        return ".ao.editing " + s[len(".editing "):]
    out = ".ao " + s
    # A block shown on its own (the editor canvas) is not inside a .mat wrapper: give it the same treatment.
    m = re.match(r"\.mat-(light|dark) (.+)", s)
    if m:
        out += ',.ao .ao-b[data-mat="%s"] %s' % (m.group(1), m.group(2))
    return out

def scope_selectors(sels: str) -> str:
    parts, depth, cur = [], 0, ""
    for ch in sels:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return ",".join(scope_selector(p) for p in parts if p.strip())

def scope(css: str) -> str:
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            break
        head = css[i:j].strip()
        # find the matching close brace
        depth, k = 1, j + 1
        while k < n and depth:
            depth += css[k] == "{"
            depth -= css[k] == "}"
            k += 1
        body = css[j + 1:k - 1]
        head = re.sub(r"/\*.*?\*/", "", head, flags=re.S).strip()
        if head.startswith("@keyframes") or head.startswith("@font-face"):
            out.append(head + "{" + body + "}")
        elif head.startswith("@"):
            out.append(head + "{" + scope(body) + "}")
        elif head == "body":
            # The page body: colours and type go on the .ao wrapper; the page background, side padding and
            # overflow stay on <body>, but only on pages that actually hold aoost blocks.
            decls = [d.strip() for d in body.replace("\n", " ").split(";") if d.strip()]
            page = [d for d in decls if re.match(r"(background|padding-left|padding-right|overflow-x)\s*:", d)]
            rest = [d for d in decls if d not in page]
            out.append(".ao{" + ";".join(rest) + "}")
            out.append("body:has(.ao.wrap){" + ";".join(page).replace("var(--paper)", "#EFF0EC") + "}")
        else:
            out.append(scope_selectors(head) + "{" + body.strip() + "}")
        i = k
    return "\n".join(out)

def region(name):
    text = "\n".join("\n".join(lines[a - 1:b]) for a, b in REGIONS[name])
    return scope(text)

def write(path, const, css, doc):
    path.parent.mkdir(parents=True, exist_ok=True)
    body = css.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    path.write_text("// Generated by scripts/port-aoost-css.py from the original index.html. Do not edit by hand.\n// %s\nexport const %s = `\n%s\n`;\n" % (doc, const, body))

write(OUT / "kit.base.styles.ts", "kitBaseCss", region("kit"), "Tokens, type, section heads, buttons, cutting mats: shared by every aoost block.")
write(OUT / "kit.after.styles.ts", "kitAfterCss", region("kitAfter"), "Late mode, ghost cursors and reduced-motion overrides: must come after the blocks' own CSS.")
for name in REGIONS:
    if name.startswith("Aoost"):
        write(OUT / name / (name + ".styles.ts"), "css", region(name), "Styles lifted from the original %s section." % name.replace("Aoost", "").lower())
print("wrote", len(REGIONS), "style files")
